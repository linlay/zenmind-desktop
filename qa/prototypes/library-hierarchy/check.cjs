// Isolated Chromium interaction checks for the standalone HTML prototype.
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'library-hierarchy-qa-'));
app.setPath('userData', path.join(output, 'profile'));
const errors = [];
let win;
const js = source => win.webContents.executeJavaScript(source).catch(error => { console.error("Evaluation failed:", source); throw error; });
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(source) {
  for (let i = 0; i < 120; i++) { if (await js(source)) return; await delay(20); }
  throw new Error('Timed out: ' + source);
}
const click = selector => js('document.querySelector(' + JSON.stringify(selector) + ').click()');
const input = (selector, value) => js('(()=>{const el=document.querySelector(' + JSON.stringify(selector) + ');el.value=' + JSON.stringify(value) + ';el.dispatchEvent(new Event("input",{bubbles:true}));})()');
const navigate = id => js('window.libraryPrototype.navigate("folder",' + JSON.stringify(id) + ')');
async function screenshot(name) { await delay(100); fs.writeFileSync(path.join(output, name + '.png'), (await win.webContents.capturePage()).toPNG()); }
(async () => {
  await app.whenReady();
  win = new BrowserWindow({ show: false, width: 1440, height: 960, useContentSize: true, webPreferences: { contextIsolation: true, nodeIntegration: false } });
  win.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message); });
  await win.loadURL('http://127.0.0.1:4177/');
  await until('document.querySelectorAll(".file").length===6');
  assert.equal(await js('document.querySelectorAll(".folder-card").length'), 3);
  assert.equal(await js('document.querySelectorAll(".tree-node .tree-node .tree-node .tree-node").length'), 1);
  assert.equal(await js('document.querySelector("#view-title").textContent'), '产品与研发');
  assert.equal(await js('document.querySelector(".topbar").getBoundingClientRect().height'),44);
  assert.equal(await js('document.querySelector("[data-action=theme]")'),null);
  await screenshot('desktop-light');
  await navigate('october');
  assert.equal(await js('document.querySelectorAll(".crumbs .crumb").length'), 5);
  assert.equal(await js('document.querySelectorAll(".file").length'), 2);
  await screenshot('deep-hierarchy');
  await click('.crumbs [data-id="product"]');
  assert.equal(await js('document.querySelectorAll(".file").length'), 6);
  await click('.head-actions [data-action="new-folder"]');
  await input('#dialog-input', '发布材料');
  await js('document.querySelector("#text-form").dispatchEvent(new Event("submit",{bubbles:true,cancelable:true}))');
  assert.equal(await js('window.libraryPrototype.getState().folders.some(f=>f.name==="发布材料"&&f.parent==="product")'), true);
  await click('.head-actions [data-action="new-folder"]');
  await input('#dialog-input', '发布材料');
  await js('document.querySelector("#text-form").dispatchEvent(new Event("submit",{bubbles:true,cancelable:true}))');
  assert.equal(await js('document.querySelector("#dialog-error").textContent.includes("同名")'), true);
  await click('[data-action="close-dialog"]');
  await click('[data-file="doc1"]');
  await click('#inspector [data-action="move"]');
  await click('[data-action="choose-destination"][data-id="october"]');
  assert.equal(await js('document.querySelectorAll(".move-dest .checked-icon").length'), 1);
  await click('[data-action="confirm-move"]');
  assert.equal(await js('window.libraryPrototype.getState().files.find(f=>f.id==="doc1").folder'), 'october');
  assert.equal(await js('document.querySelectorAll(".file").length'), 5);
  await navigate('october');
  await click('[data-file="doc1"]');
  await click('#inspector [data-action="add-tag"]');
  await input('#dialog-input', '发布准备');
  await js('document.querySelector("#text-form").dispatchEvent(new Event("submit",{bubbles:true,cancelable:true}))');
  assert.equal(await js('window.libraryPrototype.getState().files.find(f=>f.id==="doc1").tags.includes("发布准备")'), true);
  assert.equal(await js('document.querySelector("#tag-nav").textContent.includes("发布准备")'), true);
  await click('#inspector [data-action="star"]');
  assert.equal(await js('window.libraryPrototype.getState().files.find(f=>f.id==="doc1").star'), false);
  await click('[data-view="starred"]');
  assert.equal(await js('document.querySelector("[data-file=doc1]")'), null);
  await navigate('product');
  await click('[data-action="filter"][data-id="project"]');
  assert.equal(await js('document.querySelectorAll(".file").length'), 1);
  await click('[data-action="filter"][data-id="all"]');
  await input('#search', '需求');
  assert.equal(await js('document.querySelectorAll(".file").length'), 1);
  await input('#search', 'not-a-real-name');
  assert.equal(await js('document.querySelectorAll("#file-grid .empty").length'), 1);
  await input('#search', '');
  await click('[data-action="layout"][data-layout="list"]');
  assert.equal(await js('document.querySelector("#file-grid").classList.contains("list")'), true);
  await click('[data-action="layout"][data-layout="grid"]');
  // Move an image by drag and drop, preserving its favorite and tags.
  await js('(()=>{const source=document.querySelector("[data-file=img1]"),target=document.querySelector("[data-drop=engineering]"),dataTransfer=new DataTransfer();source.dispatchEvent(new DragEvent("dragstart",{bubbles:true,dataTransfer}));target.dispatchEvent(new DragEvent("drop",{bubbles:true,cancelable:true,dataTransfer}));})()');
  assert.equal(await js('window.libraryPrototype.getState().files.find(f=>f.id==="img1").folder'), 'engineering');
  assert.equal(await js('window.libraryPrototype.getState().files.find(f=>f.id==="img1").star'), true);
  // Bulk selection and move from the unfiled view.
  await click('[data-view="unfiled"]');
  await js('document.querySelectorAll(".file-check").forEach(input=>{input.checked=true;input.dispatchEvent(new Event("change",{bubbles:true}));})');
  // Re-render replaces the second checkbox, so explicitly select any remaining item.
  await js('[...document.querySelectorAll(".file-check:not(:checked)")].forEach(input=>{input.checked=true;input.dispatchEvent(new Event("change",{bubbles:true}));})');
  assert.equal(await js('window.libraryPrototype.getState().view.selected.length'), 2);
  await click('#selectionbar [data-action="move"]');
  await click('[data-action="choose-destination"][data-id="reports"]');
  await click('[data-action="confirm-move"]');
  assert.equal(await js('document.querySelectorAll(".file").length'), 0);
  await navigate('product');
  // All menus use the identical navigation menu shell and typography.
  await click('[data-action="workspace-menu"]');
  const navStyle = await js('(()=>{const root=document.querySelector("#menu"),row=root.querySelector(".menu-item");return {radius:getComputedStyle(root).borderRadius,background:getComputedStyle(root).backgroundColor,border:getComputedStyle(root).borderColor,font:getComputedStyle(row).fontSize,row:getComputedStyle(row).minHeight};})()');
  assert.equal(navStyle.radius, '16px'); assert.equal(navStyle.font, '14px'); assert.equal(navStyle.row, '28px');
  await js('document.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}))');
  await click('[data-file="html1"] [data-action="file-menu"]');
  const fileStyle = await js('(()=>{const root=document.querySelector("#menu"),row=root.querySelector(".menu-item");return {radius:getComputedStyle(root).borderRadius,background:getComputedStyle(root).backgroundColor,border:getComputedStyle(root).borderColor,font:getComputedStyle(row).fontSize,row:getComputedStyle(row).minHeight};})()');
  assert.deepEqual(fileStyle, navStyle);
  assert.equal(await js('(()=>{const r=document.querySelector("#menu").getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight})()'), true);
  await screenshot('menu-light');
  await js('document.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}))');
  await click('#inspector [data-action="preview"]');
  assert.equal(await js('document.querySelectorAll(".preview-content iframe").length'), 1);
  await click('[data-action="close-dialog"]');
  await js('document.documentElement.dataset.theme="dark"');
  assert.equal(await js('document.documentElement.dataset.theme'), 'dark');
  await screenshot('desktop-dark');
  await click('[data-file="html1"] [data-action="file-menu"]');
  await screenshot('menu-dark');
  await js('document.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}))');
  win.setContentSize(860,800); await delay(80);
  assert.equal(await js('document.documentElement.scrollWidth<=innerWidth'), true);
  await screenshot('compact');
  win.setContentSize(390,844); await delay(80);
  assert.equal(await js('document.documentElement.scrollWidth<=innerWidth'), true);
  await click('.hamburger');
  assert.equal(await js('document.querySelector("#app").classList.contains("sidebar-open")'), true);
  await screenshot('mobile-tree');
  await click('[data-view="folder"][data-id="october"]');
  assert.equal(await js('document.querySelector("#app").classList.contains("sidebar-open")'), false);
  await screenshot('mobile');
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(output,'passed'),'ok');
  console.log(JSON.stringify({ok:true,output,checks:['four-level tree and breadcrumb','folder creation and duplicate validation','move and drag/drop preserve original association','multi-select movement','tag editing and favorite views','type/search/empty states','grid/list modes','same navigation/file menu tokens','menu viewport containment','real HTML preview','light/dark','860px and 390px layouts','mobile tree navigation','no console errors']},null,2));
  win.destroy();app.quit();
})().catch(error=>{console.error(error, errors);if(win)win.destroy();app.exit(1);});
