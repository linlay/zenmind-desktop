const { app, BrowserWindow, dialog, screen } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { createPluginTestRuntime } = require('../test/helpers/plugin-lifecycle.cjs');
const { getDesktopWebappDataRoot } = require('../dist-electron/main/infrastructure/filesystem/user-paths');
const { DESKTOP_BROWSER_WEBVIEW_PARTITION } = require('../dist-electron/shared/browser-surfaces');
const archive = path.resolve(process.argv[2]);
const output = process.argv[3] || path.join(os.tmpdir(), 'native-notes-qa');
fs.mkdirSync(output, { recursive: true });
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'zenmind-native-notes-'));
app.setPath('userData', path.join(root, 'profile')); app.on('window-all-closed', () => {});
let runtime = createPluginTestRuntime(root), library;
const id = 'webapp-4abf37ad067b5336';
const savedPath = getDesktopWebappDataRoot(runtime.app, id) + '/state.json';
const notes = () => JSON.parse(fs.readFileSync(savedPath, 'utf8')).value.notes;
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(check, description) { for (let i = 0; i < 200; i++) { if (await check()) return; await wait(30); } throw new Error('Timed out: ' + description); }
const evaluate = (window, code) => window.webContents.executeJavaScript(code, true);
const editorReady = window => until(() => evaluate(window, 'document.getElementById("body")?.disabled === false'), 'editor ready');
const edit = (window, field, text) => evaluate(window, `document.getElementById(${JSON.stringify(field)}).value=${JSON.stringify(text)};document.getElementById(${JSON.stringify(field)}).dispatchEvent(new Event('input',{bubbles:true}))`);
const click = (window, field) => evaluate(window, `document.getElementById(${JSON.stringify(field)}).click()`);
async function saveReady(window) { await until(() => evaluate(window, 'document.getElementById("status").textContent === "已保存"'), 'note saved'); }
async function main() {
  const imported = await runtime.plugins.installFromArchive(runtime.app, archive); assert.equal(imported.ok, true, imported.message);
  assert.equal((await runtime.services.startService(runtime.app, 'sticky-notes')).ok, true);
  const started = await runtime.webs.webappRuntime.start(runtime.app, id); assert.equal(started.ok, true, started.message);
  library = new BrowserWindow({ show: false, width: 680, height: 620, webPreferences: { partition: DESKTOP_BROWSER_WEBVIEW_PARTITION, contextIsolation: true, sandbox: true, nodeIntegration: false } });
  await library.loadURL(started.state.webUrl);
  await until(() => fs.existsSync(savedPath) && notes().length === 1, 'initial note created');
  const firstId = notes()[0].id;
  await until(() => runtime.webs.webappWindowManager.documents.getWindow(id, firstId), 'first native window');
  let first = runtime.webs.webappWindowManager.documents.getWindow(id, firstId); await editorReady(first);
  await edit(first, 'title', '今天，慢慢来'); await edit(first, 'body', '把重要的小事留在眼前。\n\n下午三点，喝一杯茶。\n整理下一次产品讨论的想法。'); await saveReady(first);
  await click(first, 'new');
  await until(() => notes().length === 2, 'second note created');
  const secondId = notes().find(note => note.id !== firstId).id;
  await until(() => runtime.webs.webappWindowManager.documents.getWindow(id, secondId), 'second native window');
  const second = runtime.webs.webappWindowManager.documents.getWindow(id, secondId); await editorReady(second);
  await Promise.all([edit(first, 'body', '第一张便签独立保存。\n\n明天上午十点，准备产品讨论。'), edit(second, 'body', '第二张便签独立保存。\n\n记得给植物浇水。')]);
  await Promise.all([saveReady(first), saveReady(second)]);
  await until(() => evaluate(library, 'document.querySelectorAll(".preview").length === 2'), 'library receives document changes');
  assert.match(notes().find(note => note.id === firstId).body, /第一张/); assert.match(notes().find(note => note.id === secondId).body, /第二张/);
  await edit(second, 'title', '留一点时间给自己'); await saveReady(second);
  const area = screen.getPrimaryDisplay().workArea;
  first.setBounds({ x: area.x + Math.floor(area.width / 3), y: area.y + 60, width: 310, height: 330 });
  await click(first, 'menu-toggle'); await evaluate(first, 'document.querySelector("[aria-label=浅玫瑰]").click()');
  await click(first, 'pin'); await saveReady(first); assert.equal(first.isAlwaysOnTop(), true);
  const bounds = first.getBounds();
  await wait(200); fs.writeFileSync(path.join(output, 'mac-note.png'), (await first.webContents.capturePage()).toPNG());
  await evaluate(second, 'document.body.dataset.platform="win32"'); await wait(100);
  fs.writeFileSync(path.join(output, 'windows-style-note.png'), (await second.webContents.capturePage()).toPNG());
  assert.equal(await evaluate(first, 'document.documentElement.scrollWidth <= innerWidth'), true);
  assert.equal(await evaluate(second, 'document.documentElement.scrollHeight <= innerHeight'), true);
  await click(first, 'close'); await until(() => first.isDestroyed(), 'first window closes');
  assert.equal(second.isDestroyed(), false); assert.equal(runtime.webs.webappRuntime.getStatus(runtime.app, id).status, 'running');
  await evaluate(library, `(async()=>{const {windows}=await import('/notes-client.mjs');await windows({operation:'open',id:${JSON.stringify(firstId)}})})()`);
  first = runtime.webs.webappWindowManager.documents.getWindow(id, firstId); await editorReady(first);
  assert.deepEqual(first.getBounds(), bounds); assert.equal(first.isAlwaysOnTop(), true);
  assert.equal(await evaluate(first, 'getComputedStyle(document.body).backgroundColor'), 'rgb(246, 215, 223)');
  // Failed saves retain the editor and can be retried; native close observes beforeunload.
  const originalDialog = dialog.showMessageBoxSync; let prompts = 0;
  dialog.showMessageBoxSync = () => { prompts++; return 0; };
  await evaluate(first, 'window.originalFetch=window.fetch;window.fetch=(url,...args)=>String(url).includes("/api/notes/save")?Promise.reject(new Error("Offline fixture")):originalFetch(url,...args);void 0');
  await edit(first, 'body', '保存失败后仍保留的正文');
  await until(() => evaluate(first, 'document.getElementById("status").classList.contains("error")'), 'save error shown');
  await click(first, 'close'); await until(() => prompts > 0, 'native unsaved prompt'); assert.equal(first.isDestroyed(), false);
  dialog.showMessageBoxSync = originalDialog;
  await evaluate(first, 'window.fetch=window.originalFetch;void 0'); await click(first, 'retry'); await saveReady(first);
  library.destroy();
  await runtime.webs.webappRuntime.stopAll(runtime.app);
  assert.equal(first.isDestroyed(), true); assert.equal(second.isDestroyed(), true);
  runtime = createPluginTestRuntime(root);
  await runtime.webs.webappWindowManager.restoreDocuments(runtime.app);
  const restored = runtime.webs.webappWindowManager.documents.getWindow(id, firstId); assert.ok(restored); await editorReady(restored);
  assert.deepEqual(restored.getBounds(), bounds); assert.equal(restored.isAlwaysOnTop(), true);
  assert.equal(await evaluate(restored, 'document.getElementById("body").value'), '保存失败后仍保留的正文');
  assert.ok(runtime.webs.webappWindowManager.documents.getWindow(id, secondId));
  assert.equal((await runtime.plugins.uninstall(runtime.app, 'sticky-notes')).ok, true);
  assert.equal(restored.isDestroyed(), true);
  console.log('PASS native notes: actual plugin import, two independent editors, simultaneous saves, geometry/color/pin restore, safe close, failure/retry, fresh runtime restore, uninstall');
}
let finishing = false;
const watchdog = setTimeout(() => finish(1, new Error('Native notes QA timeout')), 90000);
async function finish(code, error) {
  if (finishing) return; finishing = true; clearTimeout(watchdog); if (error) console.error(error);
  if (library && !library.isDestroyed()) library.destroy();
  await runtime.webs.webappRuntime.stopAll(runtime.app);
  fs.rmSync(root, { recursive: true, force: true }); app.exit(code);
}
app.whenReady().then(main).then(() => finish(0), error => finish(1, error));
