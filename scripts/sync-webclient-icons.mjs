import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const upstream = path.resolve(process.argv.find(value => value.startsWith("--source="))?.slice(9) || path.join(root, "../agent-webclient/src/shared/icons"));
const check = process.argv.includes("--check");
function output(relative, content) {
  const target = path.join(root, relative);
  if (check) {
    if (fs.readFileSync(target, "utf8") !== content) throw new Error(`WebClient icon mirror is stale: ${relative}`);
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
}
const header = "// Generated by scripts/sync-webclient-icons.mjs from agent-webclient.\n// Do not edit this mirror directly.\n";
output("src/renderer/components/icons/agentAppearance.ts", header + fs.readFileSync(path.join(upstream, "agentAppearance.ts"), "utf8"));
output("src/renderer/components/icons/materialRegistry.ts", header + fs.readFileSync(path.join(upstream, "material/registry.ts"), "utf8"));
output("src/renderer/components/icons/material-sprite.svg", fs.readFileSync(path.join(upstream, "material/sprite.svg"), "utf8"));
const names = ["general", "coder", "kbase", "team", "executor", "proxy"];
const cases = names.map(name => {
  let source = fs.readFileSync(path.join(upstream, `agent-icons/${name}.svg`), "utf8").trim();
  if (!source.startsWith('<svg viewBox="20 35 160 145"')) throw new Error(`Unexpected Agent viewBox: ${name}`);
  source = source.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "")
    .replace(/class=/g, "className=").replace(/stroke-linecap=/g, "strokeLinecap=")
    .replace(/stroke-linejoin=/g, "strokeLinejoin=").replace(/style="stroke-width:([\d.]+)"/g, "strokeWidth={$1}")
    .replace(/id="mask-main-3"/g, "id={maskId}").replace(/mask="url\(#mask-main-3\)"/g, "mask={`url(#${maskId})`}");
  return `    case "${name}": return <>${source}</>;`;
});
output("src/renderer/components/icons/AgentGlyph.tsx", header + 'import { useId } from "react";\nimport type { AgentIconName } from "./agentAppearance";\n\nexport function AgentGlyph({ name }: { name: AgentIconName }) {\n  const maskId = useId();\n  switch (name) {\n' + cases.join("\n") + '\n  }\n}\n');
