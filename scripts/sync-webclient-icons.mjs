import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const upstream = path.resolve(process.argv.find(value => value.startsWith("--source="))?.slice(9) || path.join(root, "../agent-webclient/src/shared/icons"));
const check = process.argv.includes("--check");
function output(relative, content) {
  const target = path.join(root, relative);
  if (check) {
    if (fs.readFileSync(target, "utf8") !== content) throw new Error(`WebClient icon mirror is stale: ${relative}`);
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
}
const header = "// Generated by scripts/sync-webclient-icons.mjs from agent-webclient.\n// Do not edit this mirror directly.\n";
output("src/renderer/components/icons/agentAppearance.ts", header + fs.readFileSync(path.join(upstream, "agentAppearance.ts"), "utf8"));
output("src/renderer/components/icons/materialRegistry.ts", header + fs.readFileSync(path.join(upstream, "material/registry.ts"), "utf8"));
output("src/renderer/components/icons/material-sprite.svg", fs.readFileSync(path.join(upstream, "material/sprite.svg"), "utf8"));
// Keep the same pose, CSS clocks and shared-document pointer lifecycle as WebClient.
for (const file of ["AgentDefaultPose.tsx", "AgentCharacter.module.css", "agentCharacterState.ts", "agentPointerModel.ts", "agentPointerRuntime.ts"]) {
  const notice = file.endsWith(".css") ? "/* Generated by scripts/sync-webclient-icons.mjs from agent-webclient. */\n" : header;
  output(`src/renderer/components/icons/${file}`, notice + fs.readFileSync(path.join(upstream, file), "utf8"));
}
