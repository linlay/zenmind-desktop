import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { pathToFileURL } from "node:url";

const hash = bytes => crypto.createHash("sha256").update(bytes).digest("hex");

/** Read-only verification, usable for source bundles, app resources and deployed dist. */
export function readWebclientAssetFingerprint(distRoot) {
  const root = fs.realpathSync(distRoot);
  const files = new Set(["index.html"]);
  const read = relative => {
    const filename = fs.realpathSync(path.resolve(root, relative));
    const resolved = path.relative(root, filename);
    if (resolved.startsWith(`..${path.sep}`) || resolved === ".." || path.isAbsolute(resolved)) {
      throw new Error(`WebClient asset escapes dist: ${relative}`);
    }
    return fs.readFileSync(filename);
  };
  const html = read("index.html").toString("utf8");
  for (const match of html.matchAll(/\b(?:src|href)=["']([^"']+)["']/gu)) {
    const url = new URL(match[1], "http://webclient.invalid");
    if (url.origin !== "http://webclient.invalid" || !/\.(?:js|css)$/u.test(url.pathname)) continue;
    // Generated by the running HTTP host, not part of the compiled application.
    if (url.pathname === "/runtime-config.js") continue;
    const relative = decodeURIComponent(url.pathname).replace(/^\//u, "");
    read(relative); // Fail for dangling HTML references, even if hashes otherwise agree.
    files.add(relative);
  }
  const walk = relative => {
    const dir = path.join(root, relative);
    if (!fs.existsSync(dir)) return;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) throw new Error(`Unexpected WebClient asset symlink: ${entry.name}`);
      const child = `${relative}/${entry.name}`;
      if (entry.isDirectory()) walk(child);
      else if (/\.(?:js|css)$/u.test(entry.name)) files.add(child);
    }
  };
  walk("js"); walk("css");
  if (![...files].some(file => file.endsWith(".js"))) throw new Error("WebClient dist has no application JavaScript");
  const assets = Object.fromEntries([...files].sort().map(file => [file, hash(read(file))]));
  return { fingerprint: hash(JSON.stringify(assets)), assets };
}

export function verifyWebclientAssets(reference, candidates) {
  const expected = readWebclientAssetFingerprint(reference);
  for (const candidate of candidates) {
    const actual = readWebclientAssetFingerprint(candidate);
    if (actual.fingerprint !== expected.fingerprint) {
      const changed = [...new Set([...Object.keys(expected.assets), ...Object.keys(actual.assets)])]
        .filter(file => expected.assets[file] !== actual.assets[file]);
      throw new Error(`WebClient asset mismatch: ${candidate}\n${changed.join("\n")}`);
    }
  }
  return { fingerprint: expected.fingerprint, files: Object.keys(expected.assets).length, verified: candidates.length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  let reference;
  const candidates = [];
  for (let index = 2; index < process.argv.length; index += 2) {
    const flag = process.argv[index], value = process.argv[index + 1];
    if (!value || value.startsWith("--")) throw new Error("Expected a dist directory after each option");
    if (flag === "--reference") reference = value;
    else if (flag === "--candidate") candidates.push(value);
    else throw new Error(`Unknown option: ${flag}`);
  }
  if (!reference || !candidates.length) throw new Error("Usage: --reference DIST --candidate DIST [--candidate DIST ...]");
  console.log(JSON.stringify(verifyWebclientAssets(reference, candidates)));
}
